# analysis/metrics.py

import vectorbt as vbt
import pandas as pd

def get_summary_stats(portfolio: vbt.Portfolio) -> pd.Series:
    """
    Retrieves the summary statistics Series from a vectorbt Portfolio object.

    Args:
        portfolio: A vectorbt Portfolio object generated by from_signals.

    Returns:
        pandas Series containing various performance metrics.
    """
    try:
        # The .stats() method computes and returns a wide range of metrics
        return portfolio.stats()
    except Exception as e:
        print(f"Error getting portfolio stats: {e}")
        return pd.Series(dtype=float) # Return empty Series on error

def display_summary_stats(portfolio: vbt.Portfolio,
                          metrics_to_display: list = None):
    """
    Prints selected or all summary statistics in a formatted way.

    Args:
        portfolio: A vectorbt Portfolio object.
        metrics_to_display: Optional list of metric names (strings) to display.
                            If None, displays a default set.
    """
    try:
        stats = portfolio.stats()

        if metrics_to_display is None:
            # Define a default set of key metrics to display
            metrics_to_display = [
                'Start', 'End', 'Period', 'Start Value', 'End Value',
                'Total Return [%]', 'Benchmark Return [%]', 'Max Drawdown [%]',
                'Max Drawdown Duration', 'Total Trades', 'Win Rate [%]',
                'Best Trade [%]', 'Worst Trade [%]', 'Avg Winning Trade [%]',
                'Avg Losing Trade [%]', 'Avg Trade [%]', 'Profit Factor',
                'Expectancy', 'Sharpe Ratio', 'Sortino Ratio', 'Calmar Ratio'
            ]

        print("\n--- Backtest Performance Summary ---")
        for metric in metrics_to_display:
            if metric in stats.index:
                value = stats[metric]
                # Basic formatting for readability
                if isinstance(value, float):
                    if '%' in metric:
                         # Already percentage, format nicely
                         print(f"{metric:<25}: {value:,.2f}%")
                    elif 'Ratio' in metric or 'Factor' in metric or 'Expectancy' in metric:
                         print(f"{metric:<25}: {value:,.3f}")
                    else:
                         print(f"{metric:<25}: {value:,.2f}")
                else:
                    # Handle Timestamps, Timedeltas, or other types
                    print(f"{metric:<25}: {value}")
            else:
                print(f"{metric:<25}: N/A") # Metric not found in stats
        print("------------------------------------")

    except Exception as e:
        print(f"Error displaying portfolio stats: {e}")


def get_trade_records(portfolio: vbt.Portfolio) -> pd.DataFrame:
    """
    Retrieves the trade records in a human-readable format.

    Args:
        portfolio: A vectorbt Portfolio object.

    Returns:
        pandas DataFrame containing detailed information for each trade.
    """
    try:
        # .trades.records_readable provides a DataFrame of executed trades
        return portfolio.trades.records_readable
    except Exception as e:
        print(f"Error getting trade records: {e}")
        return pd.DataFrame() # Return empty DataFrame on error

